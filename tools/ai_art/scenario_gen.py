# --- Scenario API ---------------------------------------------------------------------------

CREDENTIALS = os.path.join(HERE, "credentials.csv")


def credentials() -> tuple[str, str]:
    """
    The API key and secret: from SCENARIO_API_KEY and SCENARIO_API_SECRET, or else from
    the key file Scenario downloads (an `id,secret` CSV) at SCENARIO_CREDENTIALS or
    tools/ai_art/credentials.csv, which git ignores.
    """
    key = os.environ.get("SCENARIO_API_KEY", "")
    secret = os.environ.get("SCENARIO_API_SECRET", "")
    if key and secret:
        return key, secret
    path = os.environ.get("SCENARIO_CREDENTIALS", CREDENTIALS)
    if os.path.exists(path):
        import csv

        with open(path, encoding="utf-8-sig") as f:
            for row in csv.DictReader(f):
                if row.get("id") and row.get("secret"):
                    return row["id"].strip(), row["secret"].strip()
    sys.exit("No Scenario key: put the downloaded key file at tools/ai_art/credentials.csv, "
             "or set SCENARIO_API_KEY and SCENARIO_API_SECRET.")


def auth_header() -> str:
    key, secret = credentials()
    return "Basic " + base64.b64encode(f"{key}:{secret}".encode()).decode()


def call(method: str, path: str, body: dict | None = None, raw: bytes | None = None, content_type: str = "application/json") -> dict:
    data = raw if raw is not None else (json.dumps(body).encode() if body is not None else None)
    req = urllib.request.Request(API + path, data=data, method=method)
    req.add_header("Authorization", auth_header())
    req.add_header("Accept", "application/json")
    if data is not None:
        req.add_header("Content-Type", content_type)
    try:
        with urllib.request.urlopen(req, timeout=120) as resp:
            return json.loads(resp.read() or b"{}")
    except urllib.error.HTTPError as e:
        raise RuntimeError(f"{method} {path}: HTTP {e.code}: {e.read().decode(errors='replace')[:600]}") from None


def find(obj, key):
    """The first value of `key` anywhere in a JSON response (Scenario nests job and asset fields)."""
    if isinstance(obj, dict):
        if key in obj:
            return obj[key]
        for v in obj.values():
            found = find(v, key)
            if found is not None:
                return found
    elif isinstance(obj, list):
        for v in obj:
            found = find(v, key)
            if found is not None:
                return found
    return None


def run_job(model: str, body: dict, dry_run: bool = False) -> list[str]:
    """Starts a generation, waits for it, returns its asset ids."""
    path = f"/generate/custom/{model}" + ("?dryRun=true" if dry_run else "")
    started = call("POST", path, body)
    if dry_run:
        print("    dry run:", json.dumps(find(started, "creativeUnitsCost") or started)[:300])
        return []
    job_id = find(started, "jobId")
    if not job_id:
        raise RuntimeError(f"No jobId in the response: {json.dumps(started)[:400]}")
    delay = 2.0
    for _ in range(200):
        time.sleep(delay)
        delay = min(delay * 1.3, 8.0)
        job = call("GET", f"/jobs/{job_id}")
        status = find(job, "status")
        if status == "success":
            return list(find(job, "assetIds") or [])
        if status in ("failed", "canceled"):
            raise RuntimeError(f"Job {job_id} {status}: {json.dumps(find(job, 'error') or job)[:400]}")
    raise RuntimeError(f"Job {job_id} still running after the time limit.")


def download(asset_id: str) -> Image.Image:
    url = find(call("GET", f"/assets/{asset_id}"), "url")
    if not url:
        raise RuntimeError(f"No url for asset {asset_id}")
    with urllib.request.urlopen(url, timeout=120) as resp:
        return Image.open(io.BytesIO(resp.read())).convert("RGBA")


def upload(source: str | Image.Image, name: str = "") -> str:
    """Uploads a local image (a path or an image) as a Scenario asset, returns its id."""
    # A reference needs no more than 1536 px; a full 2K PNG is too long a request.
    img = (Image.open(source) if isinstance(source, str) else source).convert("RGB")
    img.thumbnail((1536, 1536), Image.LANCZOS)
    buf = io.BytesIO()
    img.save(buf, "JPEG", quality=92)
    png = buf.getvalue()
    name = os.path.splitext(name or os.path.basename(source))[0] + ".jpg"
    try:
        data_url = "data:image/jpeg;base64," + base64.b64encode(png).decode()
        resp = call("POST", "/assets", {"image": data_url, "name": name})
    except RuntimeError:
        boundary = "----descender" + str(int(time.time()))
        parts = (f"--{boundary}\r\nContent-Disposition: form-data; name=\"image\"; filename=\"{name}\"\r\n"
                 "Content-Type: image/jpeg\r\n\r\n").encode() + png + f"\r\n--{boundary}--\r\n".encode()
        resp = call("POST", "/assets", raw=parts, content_type=f"multipart/form-data; boundary={boundary}")
    asset_id = find(resp, "id") or find(resp, "assetId")
    if not asset_id:
        raise RuntimeError(f"No asset id in the upload response: {json.dumps(resp)[:400]}")
    return asset_id


# --- What to make ---------------------------------------------------------------------------

def load_style() -> dict:
    with open(os.path.join(HERE, "style.json"), encoding="utf-8") as f:
        return json.load(f)


def load_overrides() -> dict:
    path = os.path.join(HERE, "prompts.json")
    if not os.path.exists(path):
        return {}
    with open(path, encoding="utf-8") as f:
        return json.load(f).get("files", {})


def rel(entry: dict) -> str:
    return entry["path"][len(ART_PREFIX):] if entry["path"].startswith(ART_PREFIX) else entry["path"]


def selected(entries: list[dict], only: list[str] | None) -> list[dict]:
    if only:
        return [e for e in entries if any(fnmatch.fnmatch(rel(e), p) for p in only)]
    return [e for e in entries
            if any(fnmatch.fnmatch(rel(e), p) for p in DEFAULT_INCLUDE)
            and not any(fnmatch.fnmatch(rel(e), p) for p in NEVER_BY_DEFAULT)
            and e.get("blend", "normal") != "additive"]


def kind(entry: dict) -> dict:
    """How one manifest entry is generated: depth, cut out or not, tiling, panels."""
    r = rel(entry)
    w, h = entry["size"]
    tile = entry.get("tileable") or []
    # repaint: the kit piece's current art is the layout, repainted in the key art's style, so
    # its silhouette, pivot and attachment rows stay where the engine expects them.
    k = {"depth": "play", "isolated": True, "tile": tile, "panels": 1, "align": "centre", "mode": "repaint"}
    if r.startswith("Backdrop_Garden/"):
        if "sky" in r:
            k.update(depth="sky", isolated=False)
        elif "bg1_far" in r:
            k.update(depth="far")
        elif "bg2_midfar" in r:
            k.update(depth="midfar")
        else:
            k.update(depth="mid")
        if w / h > RATIOS["21:9"] * 1.15:
            k["panels"] = math.ceil((w / h) / RATIOS["21:9"])
        k["align"] = "bottom"
        k["mode"] = "free"
    elif "x" in tile and "y" in tile:
        k.update(depth="fill", isolated=False, mode="texture")
    over = load_overrides().get(r, {})
    if over.get("mode"):
        k["mode"] = over["mode"]
    if over.get("panels"):
        k["panels"] = over["panels"]
    pivot = entry.get("pivot", [0.5, 0.5])
    purpose = entry.get("purpose", "").lower()
    if k["align"] == "centre":
        if "hang" in purpose or pivot[1] >= 0.95:
            k["align"] = "top"
        elif pivot[1] <= 0.05:
            k["align"] = "bottom"
    return k


def ratio_for(w: float, h: float) -> str:
    target = math.log(w / h)
    return min(RATIOS, key=lambda name: abs(math.log(RATIOS[name]) - target))


def prompt_for(entry: dict, style: dict, k: dict, overrides: dict) -> str:
    over = overrides.get(rel(entry), {})
    subject = over.get("subject") or entry.get("purpose", "")
    parts = [style["style"], style["depth"][k["depth"]]]
    if k.get("mode") == "repaint":
        parts.append(style["repaintNote"])
        w, h = entry["size"]
        if w / h > RATIOS["21:9"] * 1.5:
            parts.append("The layout shows the same horizontal strip stacked several times: repaint every copy identically, as separate strips, each keeping its exact height and position.")
    elif style.get("styleReference") and style.get("referenceNote"):
        parts.append(style["referenceNote"])
    if k["isolated"] and k.get("mode") != "repaint":
        parts.append(style["isolated"])
    if "x" in k["tile"] and k["depth"] != "fill":
        parts.append("A long horizontal strip that continues past both side edges, evenly lit along its length.")
    if "y" in k["tile"] and "x" not in k["tile"]:
        parts.append("A tall vertical piece that continues past the top and bottom edges.")
    parts.append("Subject: " + subject)
    if over.get("extra"):
        parts.append(over["extra"])
    parts.append(style["avoid"])
    return " ".join(p.strip() for p in parts if p)


def texture_body(style: dict, prompt: str, side: int) -> dict:
    """A seamless surface on Scenario Texture: square, seams erased, the key art as style."""
    body = {"prompt": prompt, "width": side, "height": side, "quality": "high", "eraseSeam": True}
    if style.get("styleReference"):
        body["referenceImages"] = list(style["styleReference"])
    return body


def body_for(style: dict, prompt: str, aspect: str, seed: int | None = None) -> dict:
    body = {"prompt": prompt, "aspectRatio": aspect}
    body.update(style.get("modelInputs") or {})
    if style.get("trainedModelId"):
        body["modelId"] = style["trainedModelId"]
    if style.get("styleReference"):
        body["referenceImages"] = list(style["styleReference"])
    if seed is not None and style.get("seedInput"):
        body[style["seedInput"]] = seed
    return body


# --- Repainting ----------------------------------------------------------------------------

LAYOUT_GREY = (128, 128, 128)


def strip_copies(w: int, h: int) -> int:
    """
    How many copies of a thin strip are stacked in its layout: enough to fill the canvas,
    so no empty grey is left for the model to fill with a scene of its own. Odd, so there
    is a middle copy.
    """
    if w / h <= RATIOS["21:9"] * 1.5:
        return 1
    copies = max(1, round((w / h) / RATIOS["21:9"]))
    return copies + 1 - copies % 2


def layout_image(entry: dict) -> tuple[Image.Image, list[float], str]:
    """
    The piece's current art on plain grey, padded to the nearest aspect ratio the model
    makes: the layout to repaint, where the piece sits in it (as fractions), the ratio.
    The generated original is used once `apply` has replaced it (tools/ai_art/backup).
    """
    r = rel(entry)
    src = os.path.join(BACKUP, r)
    if not os.path.exists(src):
        src = os.path.join(ROOT, entry["path"])
    piece = Image.open(src).convert("RGBA")
    w, h = entry["size"]
    piece = piece.resize((w, h), Image.LANCZOS)
    copies = strip_copies(w, h)
    stack_h = h * copies
    aspect = ratio_for(w, stack_h)
    ratio = RATIOS[aspect]
    cw, ch = (w, round(w / ratio)) if w / stack_h > ratio else (round(stack_h * ratio), stack_h)
    ch = max(ch, stack_h)
    canvas = Image.new("RGBA", (cw, ch), LAYOUT_GREY + (255,))
    top = (ch - stack_h) // 2
    for i in range(copies):
        canvas.alpha_composite(piece, ((cw - w) // 2, top + i * h))
    x0, y0 = (cw - w) // 2, top + (copies // 2) * h
    scale = 1536 / max(cw, ch)
    canvas = canvas.resize((round(cw * scale), round(ch * scale)), Image.LANCZOS)
    return canvas.convert("RGB"), [x0 / cw, y0 / ch, (x0 + w) / cw, (y0 + h) / ch], aspect


def grey_key(img: Image.Image, tolerance: int = 22, soft: int = 18) -> Image.Image:
    """
    Cuts out the layout's flat grey background locally, for pieces a background remover
    takes for background themselves (pale bands running edge to edge): a pixel near
    LAYOUT_GREY becomes transparent, fading in over `soft` levels beyond `tolerance`.
    """
    rgb = img.convert("RGB")
    diff = ImageChops.difference(rgb, Image.new("RGB", rgb.size, LAYOUT_GREY))
    r, g, b = diff.split()
    dist = ImageChops.lighter(ImageChops.lighter(r, g), b)
    alpha = dist.point(lambda d: 0 if d <= tolerance else min(255, (d - tolerance) * 255 // soft))
    out = img.convert("RGBA")
    out.putalpha(ImageChops.multiply(alpha, out.getchannel("A")))
    return out


def repaint_fit(img: Image.Image, box: list[float], entry: dict, k: dict) -> Image.Image:
    """The repainted piece cut back out of the padded layout, at the manifest's size."""
    w, h = entry["size"]
    W, H = img.size
    over = load_overrides().get(rel(entry), {})
    # stackPick: which stacked copy of a strip to keep (the box is the middle one); the model
    # sometimes merges neighbouring copies, leaving only the last one whole.
    if "stackPick" in over:
        copies = strip_copies(w, h)
        shift = (over["stackPick"] % copies - copies // 2) * (box[3] - box[1])
        box = [box[0], box[1] + shift, box[2], box[3] + shift]
    crop = img.crop((round(box[0] * W), round(box[1] * H), round(box[2] * W), round(box[3] * H)))
    # cropRaw in prompts.json: keep only part of the piece (fractions of it), e.g. the even
    # half of a shaft whose other half came out banded.
    part = load_overrides().get(rel(entry), {}).get("cropRaw")
    if part:
        cw, ch = crop.size
        crop = crop.crop((round(part[0] * cw), round(part[1] * ch), round(part[2] * cw), round(part[3] * ch)))
    out = crop.resize((w, h), Image.LANCZOS)
    for axis in ("x", "y"):
        if axis in k["tile"]:
            # A narrow seam band on cut-outs: where two different shapes cross-fade they ghost.
            out = seamless(out, axis, 0.92 if k["isolated"] else 0.8)
    return out


# --- Fitting to the manifest ----------------------------------------------------------------

def trim(img: Image.Image) -> Image.Image:
    box = img.getchannel("A").point(lambda a: 255 if a > 8 else 0).getbbox()
    return img.crop(box) if box else img


def seamless(img: Image.Image, axis: str, band: float = 0.8) -> Image.Image:
    """
    Blends the image with itself shifted by half, so its edges meet. Only the outer
    (1 - band) of each side is blended; the rest stays untouched, so details are not doubled.
    """
    w, h = img.size
    shifted = ImageChops.offset(img, w // 2 if axis == "x" else 0, h // 2 if axis == "y" else 0)
    mask = Image.new("L", img.size)
    draw = ImageDraw.Draw(mask)
    n = w if axis == "x" else h
    for i in range(n):
        t = abs(i - n / 2) / (n / 2)
        t = t * t * (3 - 2 * t)
        v = int(255 * min(1.0, max(0.0, (t - band) / (1 - band))))
        if axis == "x":
            draw.line([(i, 0), (i, h)], fill=v)
        else:
            draw.line([(0, i), (w, i)], fill=v)
    if img.mode == "RGBA" and img.getchannel("A").getextrema()[0] < 250:
        return union_blend(img, shifted, mask)
    return Image.composite(shifted, img, mask)


def column_alpha(img: Image.Image) -> list[int]:
    """How much is drawn in each column (the alpha summed down it)."""
    alpha = img.getchannel("A").resize((img.width, 64), Image.BOX)
    data = alpha.load()
    return [sum(data[x, y] for y in range(64)) for x in range(img.width)]


def valley(columns: list[int], x0: int, x1: int) -> int:
    """The emptiest column between x0 and x1: where a cut-out layer can be cut without halving a shape."""
    x0, x1 = max(0, x0), min(len(columns) - 1, x1)
    return min(range(x0, x1 + 1), key=lambda x: columns[x])


def stitch(panels: list[Image.Image], overlap: float = 0.18, blend: bool = False) -> Image.Image:
    """
    Joins panels left to right. Opaque panels cross-fade where they overlap; cut-out
    panels (mountains, islands, clouds over sky) are cut at the emptiest column of the
    overlap instead, since a cross-fade of two different shapes leaves ghosts.
    """
    h = min(p.height for p in panels)
    panels = [p.resize((round(p.width * h / p.height), h), Image.LANCZOS) for p in panels]
    # blend: cross-fade even cut-outs, for layers with no empty gaps to cut in (clouds).
    cutout = not blend and any(p.getchannel("A").getextrema()[0] < 250 for p in panels)
    ov = round(panels[0].width * overlap)
    out = panels[0]
    for p in panels[1:]:
        if cutout:
            # Cut both at an empty column: the end of `out` and the start of `p` overlap by ov.
            left = column_alpha(out.crop((out.width - ov, 0, out.width, h)))
            right = column_alpha(p.crop((0, 0, ov, h)))
            cut = min(range(ov), key=lambda x: left[x] + right[x])
            joined = Image.new("RGBA", (out.width - ov + cut + (p.width - cut), h))
            joined.paste(out.crop((0, 0, out.width - ov + cut, h)), (0, 0))
            joined.paste(p.crop((cut, 0, p.width, h)), (out.width - ov + cut, 0))
        else:
            # 0 at the left of the overlap (all `out`), 255 at its right (all `p`).
            ramp = Image.linear_gradient("L").rotate(90).resize((ov, h))
            joined = Image.new("RGBA", (out.width + p.width - ov, h))
            joined.paste(out, (0, 0))
            joined.paste(p, (out.width - ov, 0))
            under = out.crop((out.width - ov, 0, out.width, h))
            joined.paste(union_blend(under, p.crop((0, 0, ov, h)), ramp), (out.width - ov, 0))
        out = joined
    return out


def clean_alpha(img: Image.Image, low: int = 100, high: int = 200) -> Image.Image:
    """Drops a cut-out's faint veil: alpha below `low` becomes 0, ramping to full at `high`."""
    img = img.convert("RGBA")
    img.putalpha(img.getchannel("A").point(lambda a: 0 if a <= low else 255 if a >= high else (a - low) * 255 // (high - low)))
    return img


def union_blend(under: Image.Image, over: Image.Image, mask: Image.Image) -> Image.Image:
    """
    Cross-fades two cut-out images without ghosts: each pixel is as opaque as the more
    opaque of the two, and its colour is the two colours weighted by alpha and by the mask
    (0 = under, 255 = over). An ordinary cross-fade of two shapes leaves both half
    transparent and mixes in the black of empty pixels.
    """
    a, b, m = under.convert("RGBA").load(), over.convert("RGBA").load(), mask.convert("L").load()
    w, h = under.size
    out = Image.new("RGBA", (w, h))
    o = out.load()
    for y in range(h):
        for x in range(w):
            ra, ga, ba, aa = a[x, y]
            rb, gb, bb, ab = b[x, y]
            t = m[x, y] / 255
            wa, wb = aa * (1 - t), ab * t
            total = wa + wb
            if total <= 0:
                o[x, y] = (0, 0, 0, 0)
                continue
            # Alpha runs from under's at t = 0 to over's at t = 1, lifted toward the more
            # opaque of the two in between, so the ends meet each image exactly.
            lerp = aa * (1 - t) + ab * t
            alpha = lerp + (max(aa, ab) - lerp) * 4 * t * (1 - t)
            o[x, y] = (round((ra * wa + rb * wb) / total), round((ga * wa + gb * wb) / total),
                       round((ba * wa + bb * wb) / total), round(alpha))
    return out


def solid_below(img: Image.Image, threshold: int = 128) -> Image.Image:
    """
    Makes a band solid from its top edge down (the cloud sea): in every column, everything
    below the first pixel more opaque than `threshold` becomes opaque, coloured by the
    last opaque pixel above it. Panels whose bands end at different heights then join.
    """
    img = img.convert("RGBA")
    w, h = img.size
    px = img.load()
    for x in range(w):
        last = None
        for y in range(h):
            r, g, b, a = px[x, y]
            if last is None:
                if a > threshold:
                    last = (r, g, b)
                continue
            if a > threshold:
                last = (r, g, b)
                if a < 255:
                    px[x, y] = (r, g, b, 255)
            else:
                px[x, y] = last + (255,)
    return img


def wrap_cutout(img: Image.Image, margin: float = 0.12) -> Image.Image | None:
    """
    A cut-out strip made to repeat in x by trimming it to two empty columns near its
    ends, so the repeat joins in empty space. None if no column there is empty enough.
    """
    columns = column_alpha(img)
    peak = max(columns) or 1
    n = round(img.width * margin)
    a = valley(columns, 0, n)
    b = valley(columns, img.width - 1 - n, img.width - 1)
    if columns[a] > peak * 0.12 or columns[b] > peak * 0.12:
        return None
    return img.crop((a, 0, b + 1, img.height))


def fit(img: Image.Image, entry: dict, k: dict) -> Image.Image:
    w, h = entry["size"]
    tile = k["tile"]
    if k["isolated"] and k["panels"] > 1 and "x" in tile:
        if load_overrides().get(rel(entry), {}).get("trimTop"):
            # A band (the cloud sea): drop the empty sky above it before fitting.
            box = img.getchannel("A").point(lambda a: 255 if a > 8 else 0).getbbox()
            if box:
                img = img.crop((0, box[1], img.width, img.height))
        # A wide cut-out backdrop: repeat through empty sky where it can, else blend.
        wrapped = wrap_cutout(img)
        if wrapped is not None:
            return wrapped.resize((w, h), Image.LANCZOS)
        print("    note: no empty column near the ends; the repeat is blended")
        return seamless(img.resize((w, h), Image.LANCZOS), "x")
    if not k["isolated"] or ("x" in tile and "y" in tile):
        out = img.resize((w, h), Image.LANCZOS)
    elif "x" in tile:
        piece = trim(img)
        piece = piece.resize((w, max(1, round(piece.height * w / piece.width))), Image.LANCZOS)
        out = Image.new("RGBA", (w, h))
        if piece.height > h:
            piece = piece.resize((w, h), Image.LANCZOS)
        y = 0 if k["align"] == "top" else (h - piece.height if k["align"] == "bottom" else (h - piece.height) // 2)
        out.paste(piece, (0, y), piece)
    elif "y" in tile:
        piece = trim(img)
        piece = piece.resize((max(1, round(piece.width * h / piece.height)), h), Image.LANCZOS)
        out = Image.new("RGBA", (w, h))
        out.paste(piece, ((w - piece.width) // 2, 0), piece)
    else:
        piece = trim(img)
        scale = min(w / piece.width, h / piece.height)
        piece = piece.resize((max(1, round(piece.width * scale)), max(1, round(piece.height * scale))), Image.LANCZOS)
        out = Image.new("RGBA", (w, h))
        x = (w - piece.width) // 2
        y = 0 if k["align"] == "top" else (h - piece.height if k["align"] == "bottom" else (h - piece.height) // 2)
        out.paste(piece, (x, y), piece)
    if k["depth"] == "fill":
        return out
    for axis in ("x", "y"):
        if axis in tile:
            out = seamless(out, axis)
    return out


def contact_sheet(paths: list[str], dest: str) -> None:
    thumbs = []
    for p in paths:
        im = Image.open(p).convert("RGBA")
        im.thumbnail((360, 240))
        tile = Image.new("RGBA", (380, 270), (96, 140, 200, 255))
        tile.paste(im, ((380 - im.width) // 2, (250 - im.height) // 2), im)
        ImageDraw.Draw(tile).text((6, 252), os.path.relpath(p, OUT)[-60:], fill=(255, 255, 255, 255))
        thumbs.append(tile)
    if not thumbs:
        return
    cols = min(4, len(thumbs))
    sheet = Image.new("RGBA", (cols * 380, math.ceil(len(thumbs) / cols) * 270))
    for i, t in enumerate(thumbs):
        sheet.paste(t, ((i % cols) * 380, (i // cols) * 270))
    sheet.save(dest)


