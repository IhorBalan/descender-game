def cmd_gen(args) -> None:
    style = load_style()
    overrides = load_overrides()
    made = []
    entries = selected(manifest(), args.only)
    for n, e in enumerate(entries, 1):
        r = rel(e)
        dest = os.path.join(OUT, r)
        if os.path.exists(dest) and not args.force:
            print(f"[{n}/{len(entries)}] {r}: already generated (use --force to redo)")
            made.append(dest)
            continue
        if overrides.get(r, {}).get("derive"):
            print(f"[{n}/{len(entries)}] {r}: derived from {overrides[r]['derive']['from']} (run `derive`)")
            continue
        k = kind(e)
        w, h = e["size"]
        prompt = prompt_for(e, style, k, overrides)
        aspect = "21:9" if k["panels"] > 1 else ratio_for(w, h)
        print(f"[{n}/{len(entries)}] {r}: {k['panels']} x {aspect}, {k['depth']}, {'cutout' if k['isolated'] else 'opaque'}")
        # The asset ids of every finished step, so a failure later never pays for a step twice.
        cache_path = dest[:-4] + ".assets.json"
        cache = json.load(open(cache_path, encoding="utf-8")) if os.path.exists(cache_path) and not args.force else {}

        def remember(step: str, asset: str) -> None:
            cache[step] = asset
            os.makedirs(os.path.dirname(cache_path), exist_ok=True)
            with open(cache_path, "w", encoding="utf-8") as f:
                json.dump(cache, f, indent=2)

        try:
            panels = []
            for p in range(k["panels"]):
                asset = cache.get(f"gen{p}")
                if asset is None and k["mode"] == "repaint":
                    layout, box, aspect = layout_image(e)
                    if "layout" not in cache:
                        os.makedirs(os.path.dirname(dest), exist_ok=True)
                        layout.save(dest[:-4] + ".layout.png")
                        remember("layout", upload(layout, os.path.basename(r)))
                        remember("box", box)
                    body = body_for(style, prompt, aspect, p)
                    body["referenceImages"] = [cache["layout"]] + list(style.get("styleReference") or [])
                    ids = run_job(style["model"], body, args.dry_run)
                    if not ids:
                        continue
                    asset = ids[0]
                    remember(f"gen{p}", asset)
                elif asset is None:
                    if k["depth"] == "fill":
                        # Surfaces through Scenario Texture, which makes them seamless itself.
                        side = 2048
                        ids = run_job(TEXTURE_MODEL, texture_body(style, prompt, side), args.dry_run)
                    else:
                        panel_prompt = prompt + ("" if k["panels"] == 1 else f" Section {p + 1} of {k['panels']} of one continuous panorama.")
                        subjects = load_overrides().get(r, {}).get("panelSubjects")
                        if subjects:
                            panel_prompt += " In this section: " + subjects[p % len(subjects)]
                        ids = run_job(style["model"], body_for(style, panel_prompt, aspect, p), args.dry_run)
                    if not ids:
                        continue
                    asset = ids[0]
                    remember(f"gen{p}", asset)
                if k["isolated"] and load_overrides().get(r, {}).get("remover") == "greykey":
                    panels.append(grey_key(download(asset)))
                    continue
                if k["isolated"]:
                    cut = cache.get(f"cut{p}")
                    if cut is None:
                        remover = load_overrides().get(r, {}).get("remover", BACKGROUND_REMOVER)
                        body = {"image": asset, "hdBackgroundRemoval": True} if remover == BACKGROUND_REMOVER else {"image": asset}
                        cut = run_job(remover, body)[0]
                        remember(f"cut{p}", cut)
                    asset = cut
                panels.append(download(asset))
            if not panels:
                continue
            blend = load_overrides().get(r, {}).get("stitch") == "blend"
            if load_overrides().get(r, {}).get("solidBelow"):
                panels = [solid_below(p) for p in panels]
            if k["isolated"] and k["panels"] > 1:
                panels = [clean_alpha(p) for p in panels]
            raw = stitch(panels, blend=blend) if len(panels) > 1 else panels[0]
            os.makedirs(os.path.dirname(dest), exist_ok=True)
            raw.save(dest[:-4] + ".raw.png")
            if k["mode"] == "repaint":
                repaint_fit(raw, cache["box"] if "box" in cache else layout_image(e)[1], e, k).save(dest)
            else:
                fit(raw, e, k).save(dest)
            with open(dest[:-4] + ".prompt.txt", "w", encoding="utf-8") as f:
                f.write(prompt + "\n")
            made.append(dest)
            if any(key in e for key in ("surfaceRow", "walkableRow", "railTopRow", "springingRow", "attachRow", "hangRow", "footRow")):
                print("    note: has alignment rows in the manifest; check it lines up in the game before keeping it")
        except RuntimeError as err:
            print(f"    failed: {err}")
    if made:
        contact_sheet(made, os.path.join(OUT, "contact.png"))
        print(f"Contact sheet: {os.path.relpath(os.path.join(OUT, 'contact.png'), ROOT)}")


def cmd_derive(args) -> None:
    """
    Pieces made from other generated pieces instead of generating them (prompts.json
    "derive"): a layer shifted, flipped, hazed toward a colour, brightened or blurred,
    or an emissive mask cut from a piece's brightest warm pixels.
    """
    overrides = load_overrides()
    for e in selected(manifest(), args.only):
        r = rel(e)
        rule = overrides.get(r, {}).get("derive")
        if not rule:
            continue
        src = os.path.join(OUT, rule["from"])
        if not os.path.exists(src):
            print(f"{r}: {rule['from']} is not generated yet")
            continue
        img = Image.open(src).convert("RGBA")
        if rule.get("glow"):
            # Emissive: only the bright, warm parts (the lit crown), on transparent black.
            r_, g_, b_, a_ = img.split()
            lum = Image.merge("RGB", (r_, g_, b_)).convert("L")
            warm = ImageChops.subtract(r_, b_)
            mask = ImageChops.multiply(lum.point(lambda v: max(0, (v - 175) * 3)), warm.point(lambda v: min(255, v * 4)))
            mask = ImageChops.multiply(mask, a_).filter(ImageFilter.GaussianBlur(2))
            glow = Image.new("RGBA", img.size, (0, 0, 0, 0))
            glow.paste(img, (0, 0), mask)
            img = glow
        if rule.get("offset"):
            img = ImageChops.offset(img, round(rule["offset"] * img.width), 0)
        if rule.get("flip"):
            img = img.transpose(Image.FLIP_LEFT_RIGHT)
        if rule.get("haze"):
            colour, amount = rule["haze"]
            tint = Image.new("RGBA", img.size, tuple(colour) + (255,))
            mixed = Image.blend(img, tint, amount)
            mixed.putalpha(img.getchannel("A"))
            img = mixed
        if rule.get("brightness"):
            rgb = img.convert("RGB").point(lambda v: min(255, round(v * rule["brightness"])))
            rgb.putalpha(img.getchannel("A"))
            img = rgb
        if rule.get("blur"):
            img = img.filter(ImageFilter.GaussianBlur(rule["blur"]))
        img = img.resize(tuple(e["size"]), Image.LANCZOS)
        dest = os.path.join(OUT, r)
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        img.save(dest)
        print(f"derived {r} from {rule['from']}")


def cmd_apply(args) -> None:
    for e in selected(manifest(), args.only):
        r = rel(e)
        src = os.path.join(OUT, r)
        if not os.path.exists(src):
            continue
        target = os.path.join(ROOT, e["path"])
        backup = os.path.join(BACKUP, r)
        if os.path.exists(target) and not os.path.exists(backup):
            os.makedirs(os.path.dirname(backup), exist_ok=True)
            shutil.copy2(target, backup)
        shutil.copy2(src, target)
        print(f"applied {r}")


def cmd_restore(args) -> None:
    for e in selected(manifest(), args.only):
        r = rel(e)
        backup = os.path.join(BACKUP, r)
        if os.path.exists(backup):
            shutil.copy2(backup, os.path.join(ROOT, e["path"]))
            print(f"restored {r}")


