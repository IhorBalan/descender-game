#!/usr/bin/env python3
"""Paradise's art through Scenario (scenario.com), driven by the art manifest.

Every image the game uses is listed in Assets/Art/Paradise/manifest.json with its
size, pivot, layer and purpose. This script turns each entry into a prompt built
from the style bible (tools/ai_art/style.json), generates it on Scenario, removes
the background where the piece is cut out, and fits the result to the manifest:
exact size, the pivot's edge kept (feet down, hanging pieces from the top),
seamless repeats for tileable pieces, and very wide backdrops stitched from
several panels. Nothing in Assets/ changes until `apply`, which keeps the
generated originals in tools/ai_art/backup/.

    python tools/ai_art/scenario_gen.py check                 # credentials, model inputs
    python tools/ai_art/scenario_gen.py keyart --n 4          # zone 1 key art to pick a style from
    python tools/ai_art/scenario_gen.py upload out/keyart/keyart_2.png   # the chosen one, as a style reference
    python tools/ai_art/scenario_gen.py list                  # what `gen` would make
    python tools/ai_art/scenario_gen.py gen --only "Kit/Nature/*"
    python tools/ai_art/scenario_gen.py apply --only "Kit/Nature/*"
    python tools/ai_art/scenario_gen.py restore --only "Kit/Nature/*"

Credentials come from the environment only: SCENARIO_API_KEY and
SCENARIO_API_SECRET (Project Settings > API Keys on scenario.com). After
`apply`, run Descender > Paradise > Rebuild zone 1 in Unity, or the route bot,
to see the new art in place.

Needs only Python 3 and Pillow.
"""
